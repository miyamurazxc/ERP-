<?php

// Этот файл - контроллер админской страницы "Пользователи и роли".
// Контроллер принимает действия с сайта: открыть список пользователей,
// создать пользователя, изменить роль, одобрить регистрацию или удалить аккаунт.
namespace App\Http\Controllers;

// Модель User связывает PHP-код с таблицей users в базе данных.
// Через нее мы ищем, создаем, обновляем и удаляем пользователей.
use App\Models\User;
// RedirectResponse означает, что метод вернет не страницу, а перенаправление назад.
// Например после сохранения роли пользователь остается на странице админки.
use Illuminate\Http\RedirectResponse;
// Request хранит все данные текущего HTTP-запроса:
// данные формы, параметры поиска из URL и текущего авторизованного пользователя.
use Illuminate\Http\Request;
// Str - помощник Laravel для работы со строками.
// Здесь он нужен, чтобы искать роли без учета больших и маленьких букв.
use Illuminate\Support\Str;
// Rule нужен для проверки, что выбранная роль входит в разрешенный список ролей.
use Illuminate\Validation\Rule;
// View означает, что метод вернет Blade-страницу.
use Illuminate\View\View;

// Класс AdminUserController управляет пользователями в админке.
// Его методы вызываются из routes/web.php, когда пользователь открывает /admin/users
// или отправляет формы создания, редактирования, одобрения и удаления.
class AdminUserController extends Controller
{
    // Метод index показывает страницу "Пользователи и роли".
    // На сайте он нужен, чтобы админ/директор видел список сотрудников и мог их искать.
    public function index(Request $request): View
    {
        // Проверяем, имеет ли текущий пользователь право управлять пользователями.
        // Если обычный работник попытается открыть админку, Laravel покажет ошибку 403.
        abort_unless($request->user()->canManageUsers(), 403);

        // Берем поисковую строку q из URL, например /admin/users?q=admin.
        // trim убирает лишние пробелы, чтобы поиск " admin " работал как "admin".
        $search = trim((string) $request->query('q', ''));
        // Начинаем строить запрос к таблице users и сортируем пользователей по имени.
        // Здесь база еще не загружается, мы только готовим SQL-запрос.
        $usersQuery = User::query()->orderBy('name');

        // Если строка поиска не пустая, добавляем фильтры поиска.
        if ($search !== '') {
            // Переводим поиск в нижний регистр, чтобы "Админ" и "админ" искались одинаково.
            $normalizedSearch = Str::lower($search);

            // Ищем роли, которые подходят под введенный текст.
            // Например пользователь пишет "кадровик", а в базе роль хранится как "hr".
            $matchingRoleKeys = collect(User::availableRoles())
                // Проверяем и русское название роли ($label), и технический ключ роли ($key).
                ->filter(fn (string $label, string $key) => Str::contains(Str::lower($label.' '.$key), $normalizedSearch))
                // Берем только технические ключи найденных ролей: employee, hr, director, admin.
                ->keys()
                // Превращаем Laravel-коллекцию обратно в обычный PHP-массив.
                ->all();

            // Добавляем к запросу поиск по имени, email и роли.
            // where(function ...) группирует условия, чтобы OR работал только внутри поиска.
            $usersQuery->where(function ($query) use ($normalizedSearch, $matchingRoleKeys) {
                $query
                    // Ищем совпадение в имени пользователя.
                    ->whereRaw('LOWER(name) LIKE ?', ['%'.$normalizedSearch.'%'])
                    // Или ищем совпадение в email.
                    ->orWhereRaw('LOWER(email) LIKE ?', ['%'.$normalizedSearch.'%'])
                    // Или ищем совпадение в технической роли, например admin или director.
                    ->orWhereRaw('LOWER(role) LIKE ?', ['%'.$normalizedSearch.'%']);

                // Если поиск совпал с русским названием роли, ищем пользователей по этим ролям.
                // Например "директор" превращается в role = director.
                if ($matchingRoleKeys !== []) {
                    $query->orWhereIn('role', $matchingRoleKeys);
                }
            });
        }

        // Возвращаем Blade-страницу resources/views/admin/users.blade.php.
        // Вторым параметром передаем данные, которые страница будет показывать.
        return view('admin.users', [
            // currentUser нужен странице, чтобы знать, кто сейчас вошел в систему.
            'currentUser' => $request->user(),
            // get() выполняет SQL-запрос и получает пользователей из базы данных.
            'users' => $usersQuery->get(),
            // search нужен, чтобы после поиска текст остался в поле поиска.
            'search' => $search,
            // roles нужен для выпадающего списка ролей в форме создания и редактирования.
            'roles' => User::availableRoles(),
        ]);
    }

    // Метод store создает нового пользователя через админку.
    // Он вызывается, когда админ заполняет форму "Создать пользователя" и нажимает кнопку.
    public function store(Request $request): RedirectResponse
    {
        // Защита: создавать пользователей может только тот, у кого есть право manage_users.
        abort_unless($request->user()->canManageUsers(), 403);

        // Проверяем данные формы перед записью в базу.
        // Если данные неправильные, Laravel сам вернет пользователя назад с ошибками.
        $data = $request->validate([
            // Имя обязательно, должно быть строкой и не длиннее 255 символов.
            'name' => ['required', 'string', 'max:255'],
            // Email обязателен, должен быть email-адресом и не должен повторяться в таблице users.
            'email' => ['required', 'email', 'max:255', 'unique:users,email'],
            // Пароль обязателен, должен быть строкой и минимум 6 символов.
            'password' => ['required', 'string', 'min:6'],
            // Роль обязательна и должна быть только из списка ролей User::availableRoles().
            // Так нельзя отправить несуществующую роль через измененный HTML.
            'role' => ['required', Rule::in(array_keys(User::availableRoles()))],
        ]);

        // Создаем нового пользователя в таблице users.
        User::create([
            // Записываем имя из проверенных данных.
            'name' => $data['name'],
            // Записываем email из проверенных данных.
            'email' => $data['email'],
            // Записываем пароль. В модели User Laravel хэширует его перед сохранением.
            'password' => $data['password'],
            // Назначаем выбранную роль: candidate, employee, hr, director или admin.
            'role' => $data['role'],
            // Права не выбираются вручную.
            // Система сама назначает права по выбранной роли.
            'permissions' => $this->permissionsForRole($data['role']),
            // Пользователь, созданный админом, сразу считается одобренным.
            // В отличие от самостоятельной регистрации, ему не нужно ждать подтверждения.
            'is_approved' => true,
        ]);

        // Возвращаемся назад на страницу пользователей и показываем зеленое сообщение успеха.
        return back()->with('success', 'Пользователь создан.');
    }

    // Метод update меняет роль существующего пользователя.
    // Он вызывается из модального окна редактирования пользователя.
    public function update(Request $request, User $user): RedirectResponse
    {
        // Проверяем, что текущий пользователь имеет право управлять пользователями.
        abort_unless($request->user()->canManageUsers(), 403);

        // Проверяем, что новая роль существует в списке разрешенных ролей.
        $data = $request->validate([
            'role' => ['required', Rule::in(array_keys(User::availableRoles()))],
        ]);

        // Обновляем выбранного пользователя.
        $user->update([
            // Сохраняем новую роль.
            'role' => $data['role'],
            // Сразу пересчитываем права под эту роль.
            // Например если поставить роль "Кадровик", пользователь получит права кадровика.
            'permissions' => $this->permissionsForRole($data['role']),
        ]);

        // Возвращаемся назад и показываем сообщение об успешном обновлении.
        return back()->with('success', 'Роль пользователя обновлена.');
    }

    // Метод destroy удаляет пользователя.
    // Он вызывается, когда админ нажимает кнопку с корзиной в таблице пользователей.
    public function destroy(Request $request, User $user): RedirectResponse
    {
        // Удалять пользователей может только пользователь с правом управления пользователями.
        abort_unless($request->user()->canManageUsers(), 403);

        // Защита от удаления самого себя.
        // Если админ удалит свой аккаунт, он может потерять доступ к системе.
        if ($request->user()->is($user)) {
            return back()->with('error', 'Нельзя удалить самого себя.');
        }

        // Удаляем пользователя из таблицы users.
        $user->delete();

        // Возвращаемся назад и показываем сообщение.
        return back()->with('success', 'Пользователь удален.');
    }

    // Метод approve одобряет пользователя, который зарегистрировался сам.
    // После регистрации новый пользователь ждет решения админа.
    public function approve(Request $request, User $user): RedirectResponse
    {
        // Одобрять доступ может только админ/директор с правом управления пользователями.
        abort_unless($request->user()->canManageUsers(), 403);

        // Меняем статус доступа пользователя.
        $user->update([
            // true означает, что пользователь получил доступ к системе.
            'is_approved' => true,
            // false означает, что он больше не считается отклоненным.
            'is_rejected' => false,
        ]);

        // Возвращаемся назад с сообщением.
        return back()->with('success', 'Пользователь одобрен.');
    }

    // Метод reject отклоняет пользователя, который зарегистрировался сам.
    // Такой пользователь не сможет нормально войти и пользоваться системой.
    public function reject(Request $request, User $user): RedirectResponse
    {
        // Отклонять регистрацию может только пользователь с правом управления пользователями.
        abort_unless($request->user()->canManageUsers(), 403);

        // Меняем статус доступа пользователя.
        $user->update([
            // false означает, что пользователь не одобрен.
            'is_approved' => false,
            // true означает, что заявка на доступ отклонена.
            'is_rejected' => true,
        ]);

        // Возвращаемся назад с сообщением.
        return back()->with('success', 'Пользователь отклонен.');
    }

    // Внутренний метод, который возвращает права для выбранной роли.
    // private значит, что этот метод нельзя вызвать напрямую через route или из другого класса.
    private function permissionsForRole(string $role): array
    {
        // User::defaultPermissionsByRole() хранит стандартные права всех ролей.
        // [$role] берет права конкретной роли.
        // ?? [] возвращает пустой массив, если роль вдруг не найдена.
        return User::defaultPermissionsByRole()[$role] ?? [];
    }
}
